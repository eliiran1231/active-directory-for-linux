    [Theory]
    [InlineData("", 0)]
    [InlineData("OI", 1)]
    [InlineData("CI", 2)]
    [InlineData("NP", 4)]
    [InlineData("IO", 8)]
    [InlineData("ID", 16)]
    public void Access_filter_retains_condition_bytes_and_unrelated_selected_sections(string flags, byte bits)
    {
        const string condition = "((@User.Age >= 18) && (@Device.Name == \"a;b(c)\"))";
        var raw = new A.RawSecurityDescriptor($"O:SYD:(A;;RP;;;WD)S:(FL;{flags};RP;;;WD;{condition})");
        var filter = Assert.IsType<A.CustomAce>(raw.SystemAcl![0]);
        Assert.Equal((AceType)21, filter.AceType);
        Assert.Equal((AceFlags)bits, filter.AceFlags);
        var payload = filter.GetOpaque()!;
        Assert.Equal(16, BinaryPrimitives.ReadInt32LittleEndian(payload));
        var sid = new SecurityIdentifier(payload, 4);
        Assert.Equal("S-1-1-0", sid.Value);
        var callback = new A.RawSecurityDescriptor($"D:(XA;;RP;;;WD;{condition})");
        Assert.Equal(((A.QualifiedAce)callback.DiscretionaryAcl![0]).GetOpaque(), payload[(4 + sid.BinaryLength)..]);
        var before = AccessFilterImage(raw);
        Assert.Throws<NotSupportedException>(() => raw.GetSddlForm(AccessControlSections.All));
        Assert.Throws<NotSupportedException>(() => raw.GetSddlForm(AccessControlSections.Audit));
        Assert.Equal("O:SYD:(A;;RP;;;WD)", raw.GetSddlForm(AccessControlSections.Owner | AccessControlSections.Access));
        Assert.Equal(before, AccessFilterImage(raw));
        var copy = new A.RawSecurityDescriptor(before, 0);
        Assert.Equal(before, AccessFilterImage(copy));
        // CustomAce.GetOpaque intentionally exposes that ACE's mutable payload;
        // a separately deserialized descriptor must still own independent bytes.
        Array.Fill(((A.CustomAce)copy.SystemAcl![0]).GetOpaque()!, (byte)0xff);
        Assert.Equal(before, AccessFilterImage(raw));
    }

    [Theory]
    [InlineData(false)]
    [InlineData(true)]
    public void Access_filter_binary_copy_keeps_unknown_malformed_and_trailing_bytes(bool system)
    {
        var valid = ((A.QualifiedAce)new A.RawSecurityDescriptor("D:(XA;;RP;;;WD;(@User.Age >= 18))").DiscretionaryAcl![0]).GetOpaque()!;
        var payloads = new List<byte[]> { Array.Empty<byte>(), new byte[4], "artx"u8.ToArray(), valid[..^4], valid.Concat(new byte[4]).ToArray(), valid.Concat(new byte[] { 1, 2, 3, 4 }).ToArray() };
        for (var position = 0; position < valid.Length; position++)
        {
            var mutated = (byte[])valid.Clone(); mutated[position] ^= 0xff; payloads.Add(mutated);
        }
        foreach (var data in payloads)
        {
            var sid = new SecurityIdentifier("S-1-1-0");
            var opaque = new byte[4 + sid.BinaryLength + data.Length];
            BinaryPrimitives.WriteInt32LittleEndian(opaque, 16); sid.GetBinaryForm(opaque, 4); data.CopyTo(opaque, 4 + sid.BinaryLength);
            var acl = new A.RawAcl(2, 1); acl.InsertAce(0, new A.CustomAce((AceType)21, (AceFlags)255, opaque));
            var raw = new A.RawSecurityDescriptor(system ? ControlFlags.SystemAclPresent : ControlFlags.DiscretionaryAclPresent, null, null, system ? acl : null, system ? null : acl);
            var before = AccessFilterImage(raw);
            var copy = new A.RawSecurityDescriptor(before, 0);
            if (system) Assert.Throws<NotSupportedException>(() => copy.GetSddlForm(AccessControlSections.All));
            else Assert.Throws<InvalidOperationException>(() => copy.GetSddlForm(AccessControlSections.All));
            Assert.Equal(before, AccessFilterImage(copy));
            Assert.Equal(before, AccessFilterImage(raw));
        }
    }

    private static byte[] AccessFilterImage(A.RawSecurityDescriptor raw)
    {
        var bytes = new byte[raw.BinaryLength]; raw.GetBinaryForm(bytes, 0); return bytes;
    }
